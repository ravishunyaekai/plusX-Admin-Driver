-- Partner Chargers — IoT tables (2 tables). Written by IoT; read by admin + station master panel.

CREATE TABLE IF NOT EXISTS partner_charger_device_data (
    charger_id           VARCHAR(50)  NOT NULL COMMENT 'Must match partner_chargers.charger_id',
    station_id           VARCHAR(50)  NOT NULL COMMENT 'Must match partner_charging_stations.station_id',
    connector_id         TINYINT      NOT NULL DEFAULT 1,
    operational_status   VARCHAR(20)  NOT NULL COMMENT 'available|occupied|charging|unavailable|fault|offline',
    session_id           VARCHAR(50)  NULL DEFAULT NULL,
    session_status       VARCHAR(20)  NULL DEFAULT NULL,
    user_label           VARCHAR(100) NULL DEFAULT NULL,
    user_ref             VARCHAR(64)  NULL DEFAULT NULL,
    started_at           DATETIME     NULL DEFAULT NULL,
    last_event_at        DATETIME     NOT NULL,
    current_power_kw     DECIMAL(10,3) NULL DEFAULT NULL,
    soc_percent          DECIMAL(5,2) NULL DEFAULT NULL,
    fault_code           VARCHAR(50)  NULL DEFAULT NULL,
    fault_message        VARCHAR(255) NULL DEFAULT NULL,
    firmware_version     VARCHAR(50)  NULL DEFAULT NULL,
    connectivity         VARCHAR(20)  NULL DEFAULT NULL,
    updated_at           DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (charger_id),
    KEY idx_partner_device_station (station_id),
    KEY idx_partner_device_status (operational_status),
    KEY idx_partner_device_last_event (last_event_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS partner_charging_session_history (
    id                   BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    session_id           VARCHAR(50)  NOT NULL,
    charger_id           VARCHAR(50)  NOT NULL,
    station_id           VARCHAR(50)  NOT NULL,
    connector_id         TINYINT      NOT NULL DEFAULT 1,
    user_label           VARCHAR(100) NULL DEFAULT NULL,
    user_ref             VARCHAR(64)  NULL DEFAULT NULL,
    start_time           DATETIME     NOT NULL,
    end_time             DATETIME     NULL DEFAULT NULL,
    duration_seconds     INT UNSIGNED NULL DEFAULT NULL,
    energy_kwh           DECIMAL(12,4) NULL DEFAULT NULL,
    meter_start_kwh      DECIMAL(12,4) NULL DEFAULT NULL,
    meter_end_kwh        DECIMAL(12,4) NULL DEFAULT NULL,
    session_status       VARCHAR(20)  NOT NULL,
    stop_reason          VARCHAR(50)  NULL DEFAULT NULL,
    avg_power_kw         DECIMAL(10,3) NULL DEFAULT NULL,
    max_power_kw         DECIMAL(10,3) NULL DEFAULT NULL,
    voltage_v            DECIMAL(8,2) NULL DEFAULT NULL,
    current_a            DECIMAL(8,2) NULL DEFAULT NULL,
    id_tag               VARCHAR(64)  NULL DEFAULT NULL,
    transaction_id       VARCHAR(64)  NULL DEFAULT NULL,
    raw_payload          JSON         NULL DEFAULT NULL,
    created_at           DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_partner_session_id (session_id),
    KEY idx_partner_hist_station_start (station_id, start_time),
    KEY idx_partner_hist_charger_start (charger_id, start_time),
    KEY idx_partner_hist_status (session_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;